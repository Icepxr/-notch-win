'use strict';
const assert = require('node:assert/strict');
const { textSize, matches } = require('../src/renderer/notes-tools');
const { edges } = require('../src/renderer/scroll-edges');
assert.equal(textSize(undefined), 13); assert.equal(textSize(NaN), 13); assert.equal(textSize('22'), 13);
assert.equal(textSize(9), 10); assert.equal(textSize(30), 22); assert.equal(textSize(14.6), 15);
assert.deepEqual(matches('one ONE one', 'one'), [[0,3],[4,7],[8,11]]);
assert.deepEqual(matches('a.*[b] a.*[b]', '.*[b]'), [[1,6],[8,13]]);
assert.deepEqual(matches('บันทึก A บันทึก', 'บันทึก'), [[0,6],[9,15]]);
assert.deepEqual(matches('İ i', 'i'), [[2,3]], 'Unicode matching keeps original selection offsets');
assert.deepEqual(matches('😀 note', 'note'), [[3,7]]);
assert.deepEqual(matches('anything', ''), []);
assert.deepEqual(edges(0, 100, 250), { start: false, end: true });
assert.deepEqual(edges(50, 100, 250), { start: true, end: true });
assert.deepEqual(edges(150, 100, 250), { start: true, end: false });
assert.deepEqual(edges(0, 100, 100), { start: false, end: false });
assert.deepEqual(edges(0, 0, 100), { start: false, end: false });
assert.deepEqual(edges(NaN, 100, 200), { start: false, end: false });
console.log('Notes tools: literal Unicode find, size bounds and source scroll-edge geometry passed');
