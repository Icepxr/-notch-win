'use strict';
const assert = require('node:assert/strict');
const Tools = require('../src/renderer/timer-tools');
const { NotchTimer } = require('../src/timer');
assert.deepEqual(Tools.preferences({ mode: 'unknown', minutes: NaN, configuration: { focus: 999, shortBreak: -8, longBreak: Infinity, interval: 99, sessions: 0 } }),
  { mode: 'timer', minutes: 5, configuration: { focus: 180, shortBreak: 1, longBreak: 15, interval: 24, sessions: 1 } });
assert.equal(Tools.moving(25, 28), 23); assert.equal(Tools.moving(1, 1000), 1); assert.equal(Tools.moving(180, -1000), 180);
assert.equal(Tools.minute(24.6), 25); assert.equal(Tools.minute(NaN), 1); assert.equal(Tools.label(65), '1h05');
assert.equal(Tools.label(60), '1h00'); assert.equal(Tools.label(180), '3h00');
let now = 10;
const timer = new NotchTimer({ now: () => now });
const configuration = { focus: 2, shortBreak: 1, longBreak: 3, interval: 2, sessions: 3 };
timer.command('start', { mode: 'pomodoro', minutes: 99, configuration });
assert.equal(timer.snapshot().duration, 120, 'Focus duration comes from the captured cycle configuration');
assert.equal(timer.snapshot().sessionNumber, 1);
configuration.focus = 180; configuration.shortBreak = 60;
timer.snapshot().configuration.focus = 150;
assert.equal(timer.snapshot().configuration.focus, 2, 'caller drafts and snapshots cannot mutate the active cycle');
timer.command('start', { mode: 'pomodoro', configuration: { focus: 10 } });
assert.equal(timer.snapshot().duration, 120, 'a second Start cannot replace an active cycle');
now += 20; timer.command('pause'); const paused = timer.snapshot().reading;
now += 10000; timer.command('resume'); assert.equal(timer.snapshot().reading, paused);
const finish = () => { now += timer.snapshot().reading + 10; assert.equal(timer.finishIfDue(), true); };
finish(); assert.equal(timer.snapshot().nextPhase, 'shortBreak');
now += 50000; assert.equal(timer.finishIfDue(), false); assert.equal(timer.snapshot().phase, 'focus', 'sleep never silently advances phases');
timer.command('next'); assert.equal(timer.snapshot().duration, 60); assert.equal(timer.snapshot().sessionNumber, 1);
finish(); timer.command('next'); assert.equal(timer.snapshot().duration, 120); assert.equal(timer.snapshot().sessionNumber, 2);
finish(); assert.equal(timer.snapshot().nextPhase, 'longBreak'); timer.command('next'); assert.equal(timer.snapshot().duration, 180);
finish(); timer.command('next'); assert.equal(timer.snapshot().sessionNumber, 3);
finish(); assert.equal(timer.snapshot().cycleFinished, true); assert.equal(timer.snapshot().canNext, false);
timer.command('next'); assert.equal(timer.snapshot().completed, true, 'the last focus completes the cycle without an extra break');
timer.command('reset'); assert.equal(timer.snapshot().hasSession, false);
timer.command('start', { mode: 'pomodoro', minutes: 1 }); assert.equal(timer.snapshot().duration, 60, 'existing minute-only callers remain compatible');
timer.command('reset'); timer.command('start', { mode: 'timer', minutes: 7, configuration: { focus: 120 } }); assert.equal(timer.snapshot().duration, 420);
timer.command('reset'); timer.command('start', { mode: 'stopwatch', configuration: { sessions: 99 } }); now += 12.5; assert.equal(timer.snapshot().reading, 12.5);
console.log('Timer source: bounded setup, captured cycles, all phases, pause/sleep and existing callers passed');
