'use strict';
const assert = require('node:assert/strict');
const { Presenter } = require('../src/renderer/media-artwork');
const images = [], paints = [];
const presenter = new Presenter({ createImage: () => { const image = {}; images.push(image); return image; }, ready: (host, image) => paints.push(image) });
const img = { src: null, removeAttribute() { this.src = null; } };
const classes = new Set();
const host = { querySelector: () => img, classList: { add: value => classes.add(value), remove: value => classes.delete(value) } };
presenter.set(host, 'old'); const staleLoad = images[0].onload, staleError = images[0].onerror;
presenter.set(host, 'new'); images[1].onload();
assert.equal(img.src, 'new'); assert.equal(classes.has('has-art'), true);
staleLoad(); staleError(); assert.equal(img.src, 'new'); assert.equal(paints.at(-1), images[1], 'stale callbacks cannot change artwork or tint');
for (let i = 0; i < 20; i++) presenter.set(host, 'new');
assert.equal(images.length, 2, 'polls and geometry changes do not reload art');
presenter.set(host, 'third'); const late = images[2].onload;
assert.equal(img.src, null, 'new tracks never inherit the previous cover');
presenter.set(host, null); late();
assert.equal(img.src, null); assert.equal(classes.has('has-art'), false); assert.equal(paints.at(-1), null);
presenter.set(host, 'broken'); images[3].onerror();
assert.equal(img.src, null); assert.equal(classes.has('has-art'), false);
console.log('Artwork: stale decode/error/clear races, deduplication and fallback passed');
